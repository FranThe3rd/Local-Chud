function mountNavIcons() {
  document.querySelectorAll("#nav-features .nav-icon[data-icon]").forEach((el) => {
    const paths = NAV_ICON_PATHS[el.dataset.icon];
    if (!paths) return;
    el.innerHTML = `
      <svg xmlns="http://www.w3.org/2000/svg" width="18" height="18" fill="currentColor" viewBox="0 0 256 256" aria-hidden="true">
        ${paths.map(([d, opacity]) => `<path d="${d}"${opacity ? ` opacity="${opacity}"` : ""}></path>`).join("")}
      </svg>
    `;
  });
}

export function initSidebar() {
  mountNavIcons();

  const toggle = document.getElementById("menu-toggle");
  const sidebar = document.getElementById("sidebar");
  if (toggle && sidebar) {
    toggle.addEventListener("click", () => sidebar.classList.toggle("open"));
  }

  document.querySelectorAll("[data-collapse]").forEach((h) => {
    h.addEventListener("click", () => {
      const next = h.nextElementSibling;
      if (next) next.hidden = !next.hidden;
    });
  });
}

export function initNav() {
  document.querySelectorAll("#nav-features li").forEach((li) => {
    li.addEventListener("click", () => {
      document.querySelectorAll("#nav-features li").forEach((x) => x.classList.remove("active"));
      li.classList.add("active");
      showPanel(li.dataset.panel || "chat");
      if (window.innerWidth < 768) {
        document.getElementById("sidebar")?.classList.remove("open");
      }
    });
  });

  document.getElementById("btn-settings")?.addEventListener("click", () => {
    showPanel("settings");
  });
}
